const SIZE = 12;

/** The pixel runs (one rect per horizontal run) and a square viewBox. */
export function techIcon(name: string) {
  const key = RULES.find(([re]) => re.test(name.toLowerCase()))?.[1] ?? "chip";
  const rows = ICONS[key];
  const width = Math.max(...rows.map((r) => r.length));
  const height = rows.length;
  const runs: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        const start = x;
        while (row[x] === "#") x++;
        runs.push({ x: start, y, w: x - start });
      } else {
        x++;
      }
    }
  });
  const ox = Math.floor((SIZE - width) / 2);
  const oy = Math.floor((SIZE - height) / 2);
  return { runs, viewBox: `${-ox} ${-oy} ${SIZE} ${SIZE}` };
}
